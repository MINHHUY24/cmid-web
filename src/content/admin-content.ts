export const adminContent: Record<AppLanguage, Record<string, string>> = {
  vi: vietnamese,
  en: english,
}

export function translateAdminText(language: AppLanguage, value: string) {
  if (language === 'vi') return value

  const exactTranslation = adminContent.en[value]
  if (exactTranslation) return exactTranslation

  return Object.entries(adminContent.en)
    .sort(([first], [second]) => second.length - first.length)
    .reduce((result, [source, translation]) => result.replaceAll(source, translation), value)
}
